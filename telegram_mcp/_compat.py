def runtime_attribute_fallback():
    """Snapshot the same objects a historical runtime star import would expose."""
    from telegram_mcp import runtime

    exports = {name: getattr(runtime, name) for name in RUNTIME_EXPORTS}

    def legacy_attribute(name):
        try:
            return exports[name]
        except KeyError:
            raise AttributeError(name) from None

    return legacy_attribute
